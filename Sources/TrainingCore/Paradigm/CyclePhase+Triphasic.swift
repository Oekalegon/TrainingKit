extension CyclePhase {
    /// Triphasic: easy running only, for returning from illness or injury.
    public static let conditioning = CyclePhase("conditioning")
    /// Triphasic: faster easy running and longer, slower sprint-type intervals.
    public static let structural = CyclePhase("structural")
    /// Triphasic: running just slower than race pace, intervals just faster.
    public static let specific = CyclePhase("specific")
}
